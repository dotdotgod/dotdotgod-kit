#!/usr/bin/env node
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { BUILT_IN_TEMPLATE_NAMES, builtInTemplateText, builtInTemplateScaffold } from "../packages/cli/src/config/templates.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const check = process.argv.includes("--check");
const changed = [];

function read(relativePath) {
  return readFileSync(join(root, relativePath), "utf8");
}

function ensureNewline(value) {
  return value.endsWith("\n") ? value : `${value}\n`;
}

function write(relativePath, content) {
  const target = join(root, relativePath);
  const next = ensureNewline(content);
  const current = existsSync(target) ? readFileSync(target, "utf8") : undefined;
  if (current === next) return;
  changed.push(relativePath);
  if (!check) {
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, next);
  }
}

function copyFile(sourceRelativePath, targetRelativePath) {
  write(targetRelativePath, read(sourceRelativePath));
}

function copyDirectory(sourceRelativeDir, targetRelativeDir) {
  const source = join(root, sourceRelativeDir);
  for (const entry of readdirSync(source, { withFileTypes: true })) {
    const sourceChild = `${sourceRelativeDir}/${entry.name}`;
    const targetChild = `${targetRelativeDir}/${entry.name}`;
    if (entry.isDirectory()) copyDirectory(sourceChild, targetChild);
    else if (entry.isFile()) copyFile(sourceChild, targetChild);
  }
}

const assets = "packages/cli/assets";
const initializer = `${assets}/initializer`;
const generatedNotice = "<!-- Generated from CLI assets by scripts/generate-adapters.mjs. Do not edit this file directly; edit the source and run `pnpm run generate`. -->";

for (const name of BUILT_IN_TEMPLATE_NAMES) {
  write(`${initializer}/templates/${name}.json`, builtInTemplateText(name));
  const files = builtInTemplateScaffold(name).filter(item => item.type === "file");
  write(`${initializer}/templates/${name}.map.md`, files.map(item => `- \`${item.path.replace(/README\.md$/, "")}\`: ${item.content.split("\n\n")[1]}`).join("\n"));
}
write(`${initializer}/templates/dotdotgod.config.json`, builtInTemplateText("software"));

function renderDocClarifyBody() {
  const contextGuidance = `## Memory-Area Context\n\nUse \`dotdotgod config <root> --json\` (or the source-checkout CLI equivalent) to obtain resolved \`config.areas\`; reuse current resolved settings already in context when the project/config has not changed. Normalize the target to a repository-relative path. Check areas in order, applying each area's \`excludePaths\` before selecting the first matching \`paths\` entry. Keep the matched area's relevant guidance in context rather than repeatedly injecting the entire configuration. If no area matches, use the document's purpose and repository conventions without inventing metadata.`;
  return `${contextGuidance}\n\n${read(`${assets}/workflows/doc-clarify.md`)}`;
}

function skill(frontmatter, title, body) {
  return `---\n${frontmatter.trim()}\n---\n\n${generatedNotice}\n\n# ${title}\n\n${body.trim()}\n`;
}

const yaml = {
  init: `interface:\n  display_name: "Project Initializer"\n  short_description: "Initialize project memory and config."\n  default_prompt: "Inspect the project, select the most appropriate available dotdotgod config template, and initialize shared project memory without replacing existing files."\n`,
  docClarify: `interface:\n  display_name: "Document Clarify"\n  short_description: "Clarify dotdotgod project documentation."\n  default_prompt: "Clarify the target docs using resolved dotdotgod memory-area guidance and direct affirmative prose while preserving established meaning and traceability."\n`,
};

write(
  "packages/pi/skills/project-initializer/SKILL.md",
  skill(
    `name: project-initializer\ndescription: Initialize or normalize shared project memory and a complete editable dotdotgod config. Use when asked to set up shared agent entrypoints, docs indexes, local-memory ignores, or dotdotgod.config.json.`,
    "Project Initializer",
    read(`${assets}/workflows/init.md`).replace("{{INIT_SCRIPT_COMMAND}}", "sh <resolved-skill-directory>/scripts/init_project.sh <project-root>"),
  ),
);
write("packages/pi/skills/project-initializer/agents/openai.yaml", yaml.init);
copyDirectory(`${initializer}/scripts`, "packages/pi/skills/project-initializer/scripts");
copyDirectory(`${initializer}/templates`, "packages/pi/skills/project-initializer/templates");
copyDirectory(`${initializer}/references`, "packages/pi/skills/project-initializer/references");
write(
  "packages/cli/assets/optional-skills/document-clarify/SKILL.md",
  skill(
    `name: document-clarify\ndescription: Clarify project documentation using resolved dotdotgod memory-area guidance and direct, concise prose. Use when asked to improve README indexes, specs, tests, architecture docs, plans, archives, or project-specific docs while preserving established meaning and traceability.`,
    "Document Clarify",
    renderDocClarifyBody(),
  ),
);
write("packages/cli/assets/optional-skills/document-clarify/agents/openai.yaml", yaml.docClarify);

if (check && changed.length > 0) {
  console.error("Generated adapter resources are out of date:");
  for (const file of changed) console.error(`- ${file}`);
  console.error("Run `pnpm run generate` to update them.");
  process.exit(1);
}

if (changed.length > 0) {
  console.log(`Generated ${changed.length} adapter resource(s).`);
} else {
  console.log("Generated adapter resources are up to date.");
}
