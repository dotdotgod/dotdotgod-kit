import { execFileSync } from 'node:child_process';
import { resolve } from 'node:path';
const helper = resolve(import.meta.dirname, 'obsidian-dev.mjs');
const expression = `(async()=>{
 const id='dotdotgod-graph-probe';
 const view=app.workspace.getLeavesOfType('graph')[0]?.view;
 if(!view) throw Error('Open a native global graph first');
 const r=view.renderer;
 await app.plugins.disablePlugin(id);
 view.dataEngine.render();
 const baseline=r.nodes.map(n=>n.id).sort();
 await app.plugins.enablePlugin(id);
 const assert=(value,message)=>{if(!value)throw Error(message)};
 assert(!!app.plugins.plugins[id],'Plugin failed to load');
 const check=()=>{
  assert(r.nodes.some(n=>n.id==='src/auth.ts'),'Missing code node');
  assert(r.nodes.some(n=>n.id==='test/auth.test.ts'),'Missing test node');
  assert(new Set(r.nodes.map(n=>n.id)).size===r.nodes.length,'Duplicate nodes');
  const links=['src/auth.ts','test/auth.test.ts','DESIGN.md'].map(t=>r.nodeLookup['REQUIREMENT.md'].forward[t]);
  links.forEach(l=>assert(l?.line,'Missing rendered link'));
  assert(links[0].line.tint===0xb9a3ff,'Wrong implementation color');
  assert(links[1].line.tint===0x70c9a2,'Wrong verification color');
  assert(links[0].line.height>links[1].line.height&&links[1].line.height>links[2].line.height,'Wrong width ordering');
  return links.map(l=>({target:l.target.id,color:l.line.tint,width:l.line.height}));
 };
 const initial=check();
 for(let i=0;i<3;i++)view.dataEngine.render();
 check();
 const pan=[r.panX,r.panY],scale=r.scale;
 r.setPan(pan[0]+30,pan[1]+20);r.setScale(scale*1.2);r.idleFrames=0;r.renderCallback();
 check();
 r.setPan(...pan);r.setScale(scale);r.idleFrames=0;r.renderCallback();
 await app.plugins.disablePlugin(id);
 assert(JSON.stringify(r.nodes.map(n=>n.id).sort())===JSON.stringify(baseline),'Unload did not restore nodes');
 assert(!r.containerEl.textContent.includes('implemented_by'),'Labels survived unload');
 await app.plugins.enablePlugin(id);
 return JSON.stringify({ok:true,initial,refreshes:3,panZoom:true,unload:true,reenabled:true});
})()`;
console.log(execFileSync(process.execPath, [helper, 'eval', expression], { encoding: 'utf8' }));
