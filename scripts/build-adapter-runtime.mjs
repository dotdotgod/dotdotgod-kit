#!/usr/bin/env node
import { copyFile, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const requestedName = process.argv.slice(2).find((argument) => !argument.startsWith('--'));
const names = requestedName ? [requestedName] : ['claude-code', 'codex', 'hermes'];
const check = process.argv.includes('--check');
const valid = new Set(['claude-code', 'codex', 'hermes']);

function projectCliPlugin() {
  return {
    name: 'dotdotgod-local-cli',
    setup(build) {
      build.onLoad({ filter: /packages\/context\/src\/project\.mjs$/ }, async (args) => {
        const source = await readFile(args.path, 'utf8');
        const replaced = source
          .replace("import { createRequire } from 'node:module';", "import { fileURLToPath } from 'node:url';")
          .replace("const require = createRequire(import.meta.url);\nconst cli = require.resolve('@dotdotgod/cli/bin/dotdotgod.mjs');", "const cli = fileURLToPath(new URL('./cli.mjs', import.meta.url));");
        if (source === replaced) throw new Error('context CLI resolver marker not found');
        return { contents: replaced, loader: 'js' };
      });
    },
  };
}

async function buildAdapter(name) {
  if (!valid.has(name)) throw new Error(`unknown adapter: ${name}`);
  const adapter = join(root, 'packages', name);
  const require = createRequire(join(adapter, 'package.json'));
  const esbuild = await import(pathToFileURL(require.resolve('esbuild/lib/main.js')).href);
  const temp = await mkdtemp(join(tmpdir(), `dotdotgod-${name}-runtime-`));
  try {
    const common = { absWorkingDir: root, bundle: true, platform: 'node', format: 'esm', target: 'node22', sourcemap: false, legalComments: 'none', logLevel: 'silent' };
    if (name !== 'hermes') await esbuild.build({
      ...common,
      stdin: {
        contents: "import { hookMain } from './packages/context/src/hooks.mjs';\nhookMain(process.argv[2] || '');\n",
        resolveDir: root,
        sourcefile: `packages/${name}/hooks/runtime-entry.mjs`,
      },
      outfile: join(temp, 'hooks-runtime.mjs'),
      banner: { js: '#!/usr/bin/env node\n// Generated by scripts/build-adapter-runtime.mjs; do not edit.' },
    });
    await esbuild.build({
      ...common,
      stdin: {
        contents: "import { startServer } from './packages/context/src/server.mjs';\nstartServer().catch((error) => { console.error(error); process.exitCode = 1; });\n",
        resolveDir: root,
        sourcefile: `packages/${name}/mcp/server-entry.mjs`,
      },
      plugins: [projectCliPlugin()],
      outfile: join(temp, 'mcp-server.mjs'),
      banner: { js: '#!/usr/bin/env node\n// Generated by scripts/build-adapter-runtime.mjs; do not edit.' },
    });
    const cliEntry = await readFile(join(root, 'packages/cli/bin/dotdotgod.mjs'), 'utf8');
    await esbuild.build({
      ...common,
      stdin: {
        contents: cliEntry.replace(/^#![^\n]*\n/u, ''),
        resolveDir: join(root, 'packages/cli/bin'),
        sourcefile: 'packages/cli/bin/dotdotgod.mjs',
      },
      external: ['@huggingface/transformers'],
      outfile: join(temp, 'cli.mjs'),
      banner: { js: '#!/usr/bin/env node\n// Generated by scripts/build-adapter-runtime.mjs; optional embedding runtime is packaged separately.' },
    });

    // Keep the parser runtime/grammars local for extracted plugins without node_modules.
    const cliRequire = createRequire(join(root, 'packages/cli/package.json'));
    const parserDirectory = dirname(cliRequire.resolve('@vscode/tree-sitter-wasm'));
    const assetDirectory = join(adapter, 'mcp/parsers');
    const parserAssets = (await readdir(parserDirectory)).filter((file) => file.endsWith('.wasm') || file === 'tree-sitter.js');
    if (!check) await mkdir(assetDirectory, { recursive: true });
    for (const asset of parserAssets) {
      const target = join(assetDirectory, asset === 'tree-sitter.js' ? 'tree-sitter.cjs' : asset);
      if (check) {
        if (!(await readFile(join(parserDirectory, asset))).equals(await readFile(target))) throw new Error(`parser asset drift: ${target}`);
      } else await copyFile(join(parserDirectory, asset), target);
    }
    for (const [licenseSource, filename] of [[join(parserDirectory, '../LICENSE'), 'LICENSE'], [join(dirname(cliRequire.resolve('ignore')), 'LICENSE-MIT'), 'IGNORE_LICENSE']]) {
      const licenseTarget = join(assetDirectory, filename);
      if (check) {
        if (!(await readFile(licenseSource)).equals(await readFile(licenseTarget))) throw new Error(`parser license drift: ${licenseTarget}`);
      } else await copyFile(licenseSource, licenseTarget);
    }

    const outputs = [
      ...(name === 'hermes' ? [] : [[join(temp, 'hooks-runtime.mjs'), join(adapter, 'hooks/runtime.mjs')]]),
      [join(temp, 'mcp-server.mjs'), join(adapter, 'mcp/server.mjs')],
      [join(temp, 'cli.mjs'), join(adapter, 'mcp/cli.mjs')],
    ];
    if (name === 'hermes') {
      await esbuild.build({ ...common, entryPoints: [join(adapter, 'mcp/bridge-entry.mjs')],
        outfile: join(temp, 'bridge.mjs'), banner: { js: '// Generated by scripts/build-adapter-runtime.mjs; do not edit.\nimport { createRequire as bridgeRequire } from "node:module";\nconst require = bridgeRequire(import.meta.url);' } });
      outputs.push([join(temp, 'bridge.mjs'), join(adapter, 'mcp/bridge.mjs')]);
      // Discover schemas from the actual generated server; no second hand-maintained contract.
      const contextRequire = createRequire(join(root, 'packages/context/package.json'));
      const { Client } = await import(pathToFileURL(contextRequire.resolve('@modelcontextprotocol/sdk/client/index.js')).href);
      const { StdioClientTransport } = await import(pathToFileURL(contextRequire.resolve('@modelcontextprotocol/sdk/client/stdio.js')).href);
      const client = new Client({ name: 'schema-generator', version: '1.0.0' });
      try {
        await client.connect(new StdioClientTransport({ command: process.execPath,
          args: [join(temp, 'mcp-server.mjs')], env: { ...process.env, DOTDOTGOD_PROJECT_ROOT: temp }, stderr: 'pipe' }));
        const listed = await client.listTools();
        await writeFile(join(temp, 'tools.json'), JSON.stringify(listed.tools, null, 2) + '\n');
      } finally { await client.close(); }
      outputs.push([join(temp, 'tools.json'), join(adapter, 'mcp/tools.json')]);
    }
    for (const [built, target] of outputs) {
      let content = await readFile(built);
      // Zod emits whitespace-only lines in JIT JavaScript templates; normalize the bridge artifact.
      if (target.endsWith('/bridge.mjs')) content = Buffer.from(content.toString('utf8').replace(/^[\t ]+$/gm, ''));
      if (check) {
        let existing;
        try { existing = await readFile(target); } catch { throw new Error(`generated runtime missing: ${target}`); }
        if (!content.equals(existing)) throw new Error(`generated runtime drift: ${target}`);
      } else {
        await mkdir(dirname(target), { recursive: true });
        await writeFile(target, content);
      }
    }
    console.log(`${name} runtime ${check ? 'current' : 'generated'}`);
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
}

for (const name of names) await buildAdapter(name);
