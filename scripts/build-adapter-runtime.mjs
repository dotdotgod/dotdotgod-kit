#!/usr/bin/env node
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { createRequire } from 'node:module';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const requestedName = process.argv.slice(2).find((argument) => !argument.startsWith('--'));
const names = requestedName ? [requestedName] : ['claude-code', 'codex'];
const check = process.argv.includes('--check');
const valid = new Set(['claude-code', 'codex']);

function projectCliPlugin() {
  return {
    name: 'dotdotgod-local-cli',
    setup(build) {
      build.onLoad({ filter: /packages\/context\/src\/project\.mjs$/ }, async (args) => {
        const source = await readFile(args.path, 'utf8');
        const replaced = source
          .replace("import { createRequire } from 'node:module';", "import { fileURLToPath } from 'node:url';")
          .replace("const require = createRequire(import.meta.url);\nconst cli = require.resolve('@dotdotgod/cli/bin/dotdotgod.mjs');", "const cli = fileURLToPath(new URL('./cli.mjs', import.meta.url));");
        if (source === replaced) throw new Error('context CLI resolver marker not found');
        return { contents: replaced, loader: 'js' };
      });
    },
  };
}

async function buildAdapter(name) {
  if (!valid.has(name)) throw new Error(`unknown adapter: ${name}`);
  const adapter = join(root, 'packages', name);
  const require = createRequire(join(adapter, 'package.json'));
  const esbuild = await import(pathToFileURL(require.resolve('esbuild/lib/main.js')).href);
  const temp = await mkdtemp(join(tmpdir(), `dotdotgod-${name}-runtime-`));
  try {
    const common = { absWorkingDir: root, bundle: true, platform: 'node', format: 'esm', target: 'node22', sourcemap: false, legalComments: 'none', logLevel: 'silent' };
    await esbuild.build({
      ...common,
      stdin: {
        contents: "import { hookMain } from './packages/context/src/hooks.mjs';\nhookMain(process.argv[2] || '');\n",
        resolveDir: root,
        sourcefile: `packages/${name}/hooks/runtime-entry.mjs`,
      },
      outfile: join(temp, 'hooks-runtime.mjs'),
      banner: { js: '#!/usr/bin/env node\n// Generated by scripts/build-adapter-runtime.mjs; do not edit.' },
    });
    await esbuild.build({
      ...common,
      stdin: {
        contents: "import { startServer } from './packages/context/src/server.mjs';\nstartServer().catch((error) => { console.error(error); process.exitCode = 1; });\n",
        resolveDir: root,
        sourcefile: `packages/${name}/mcp/server-entry.mjs`,
      },
      plugins: [projectCliPlugin()],
      outfile: join(temp, 'mcp-server.mjs'),
      banner: { js: '#!/usr/bin/env node\n// Generated by scripts/build-adapter-runtime.mjs; do not edit.' },
    });
    const cliEntry = await readFile(join(root, 'packages/cli/bin/dotdotgod.mjs'), 'utf8');
    await esbuild.build({
      ...common,
      stdin: {
        contents: cliEntry.replace(/^#![^\n]*\n/u, ''),
        resolveDir: join(root, 'packages/cli/bin'),
        sourcefile: 'packages/cli/bin/dotdotgod.mjs',
      },
      external: ['@huggingface/transformers'],
      outfile: join(temp, 'cli.mjs'),
      banner: { js: '#!/usr/bin/env node\n// Generated by scripts/build-adapter-runtime.mjs; optional embedding runtime is packaged separately.' },
    });

    const outputs = [
      [join(temp, 'hooks-runtime.mjs'), join(adapter, 'hooks/runtime.mjs')],
      [join(temp, 'mcp-server.mjs'), join(adapter, 'mcp/server.mjs')],
      [join(temp, 'cli.mjs'), join(adapter, 'mcp/cli.mjs')],
    ];
    for (const [built, target] of outputs) {
      const content = await readFile(built);
      if (check) {
        let existing;
        try { existing = await readFile(target); } catch { throw new Error(`generated runtime missing: ${target}`); }
        if (!content.equals(existing)) throw new Error(`generated runtime drift: ${target}`);
      } else {
        await writeFile(target, content);
      }
    }
    console.log(`${name} runtime ${check ? 'current' : 'generated'}`);
  } finally {
    await rm(temp, { recursive: true, force: true });
  }
}

for (const name of names) await buildAdapter(name);
